"""
Centralized State Definition for the Enterprise Agentic Compliance Pipeline.

Defines the typed graph state shared across all agents in the LangGraph workflow:
- Supervisor / Orchestrator
- Guardrail Agent (PII Sanitization & Token Mapping)
- Compliance Planner Agent (Schema Context & SQL Synthesis)
- Safety Judge Agent (LLM-as-a-Judge Evaluation & Reflection Loop)
- Execution Worker (HITL Resumption & FastMCP Relay)
"""

import uuid
from typing import Annotated, Any, Optional
from typing_extensions import TypedDict
from langchain_core.messages import BaseMessage
from langgraph.graph.message import add_messages
from pydantic import BaseModel, Field


# ==============================================================================
# Domain & Structured Sub-State Models
# ==============================================================================


class PIIEntity(BaseModel):
    """Represents a sensitive entity detected and masked by the Guardrail Agent."""

    entity_type: str = Field(..., description="Type of PII (e.g. EMAIL_ADDRESS, PERSON, PHONE_NUMBER, IBAN)")
    original_value: str = Field(..., description="The unmasked, sensitive value")
    token_mask: str = Field(..., description="The cryptographic or indexed replacement token (e.g. [MASKED_EMAIL_1])")
    start_pos: int = Field(..., description="Start character offset in the source text")
    end_pos: int = Field(..., description="End character offset in the source text")


class MigrationQuery(BaseModel):
    """A single deterministic SQL statement proposed in the compliance plan."""

    target_table: str = Field(..., description="Table modified by this statement (e.g. clients, invoices)")
    operation: str = Field(..., description="Operation type: SELECT, UPDATE, INSERT, DELETE (soft-delete)")
    sql_statement: str = Field(..., description="The executable SQL query")
    rationale: str = Field(..., description="Why this query is necessary to achieve compliance/normalization")
    is_safe: bool = Field(True, description="Flag indicating if the query passed preliminary checks")


class CompliancePlan(BaseModel):
    """The structured normalization/cleaning plan generated by the Compliance Planner Agent."""

    plan_id: str = Field(default_factory=lambda: str(uuid.uuid4()), description="Unique ID for this plan")
    summary: str = Field(..., description="High-level human-readable summary of proposed actions")
    targeted_tables: list[str] = Field(default_factory=list, description="List of tables affected")
    queries: list[MigrationQuery] = Field(default_factory=list, description="Ordered sequence of SQL queries")
    is_read_only: bool = Field(False, description="True if plan contains only non-mutating SELECT queries")
    simulated_affected_rows: int = Field(0, description="Estimated total rows affected across all queries")
    rationale: str = Field(..., description="Compliance and governance justification for the changes")


class JudgeEvaluation(BaseModel):
    """Automated evaluation and scoring emitted by the Safety Judge Agent (LLM-as-a-Judge)."""

    score: float = Field(..., ge=0.0, le=1.0, description="Numeric safety score between 0.0 and 1.0")
    passed: bool = Field(..., description="True if score >= 0.85 and no critical safety rules violated")
    verdict: str = Field(..., description="VERIFIED_SAFE, REJECTED_UNSAFE, or REVISION_REQUIRED")
    feedback: str = Field(..., description="Detailed explanation of safety findings and reasoning")
    detected_violations: list[str] = Field(default_factory=list, description="List of detected AST/security violations")
    recommendations: list[str] = Field(default_factory=list, description="Guidance for the planner if a replan is needed")


class ExecutionResult(BaseModel):
    """Result emitted by the Execution Worker after relaying approved queries to FastMCP."""

    execution_id: str = Field(..., description="Unique execution audit ID")
    status: str = Field(..., description="COMPLETED, FAILED, or ROLLED_BACK")
    queries_executed: list[str] = Field(default_factory=list, description="List of executed queries")
    total_affected_rows: int = Field(0, description="Actual count of rows modified")
    pre_images_captured: int = Field(0, description="Count of row pre-image snapshots saved for rollbacks")
    payload_s3_uri: Optional[str] = Field(None, description="MinIO S3 URI if payload exceeded 5KB offload threshold")
    error: Optional[str] = Field(None, description="Execution error message if failed")
    query_results: list[dict[str, Any]] = Field(default_factory=list, description="Retrieved rows for read-only SELECT queries")


# ==============================================================================
# Centralized LangGraph State Schema (TypedDict)
# ==============================================================================


class ComplianceState(TypedDict):
    """
    Centralized typed state dictionary for the LangGraph workflow.
    
    This state transitions across the multi-agent reasoning cluster:
    1. Guardrail Agent: populates sanitized_prompt, pii_mapping, detected_pii.
    2. Compliance Planner: populates schema_context, proposed_plan.
    3. Safety Judge: populates judge_evaluation, updates replan_count or sets PENDING_APPROVAL.
    4. HITL Gate: issues approval_token, pauses for human sign-off.
    5. Execution Worker: resumes with valid token, triggers FastMCP, populates execution_result.
    """

    # Identifiers & Metadata
    thread_id: str
    user_id: str
    created_at: str

    # Inputs & PII Sanitization (Guardrail Agent)
    original_prompt: str
    sanitized_prompt: str
    pii_mapping: dict[str, str]  # token_mask -> original_value
    detected_pii: list[dict[str, Any]]  # List of serialized PIIEntity

    # Database Context (Schema Mirror)
    schema_context: dict[str, Any]  # Tables, columns, types, and data samples

    # Planning & Reasoning (Compliance Planner)
    proposed_plan: Optional[dict[str, Any]]  # Serialized CompliancePlan

    # Safety Evaluation & Reflection (Safety Judge)
    judge_evaluation: Optional[dict[str, Any]]  # Serialized JudgeEvaluation
    replan_count: int  # Max 3 replan iterations allowed before failing

    # Governance & HITL Approval Gate
    status: str  # PENDING_REASONING, PENDING_APPROVAL, APPROVED, REJECTED, EXECUTING, COMPLETED, FAILED
    approval_token: Optional[str]  # Cryptographic HMAC-SHA256 JWT
    approved_by: Optional[str]
    approved_at: Optional[str]

    # Execution & Auditing (Execution Worker & FastMCP)
    execution_result: Optional[dict[str, Any]]  # Serialized ExecutionResult
    error_message: Optional[str]

    # LangGraph Message History (Annotated reducer)
    messages: Annotated[list[BaseMessage], add_messages]


# ==============================================================================
# State Factory & Helpers
# ==============================================================================


def create_initial_state(
    user_prompt: str,
    user_id: str = "default_compliance_officer",
    thread_id: Optional[str] = None,
) -> ComplianceState:
    """
    Creates an initialized, clean ComplianceState ready to be fed into the LangGraph orchestrator.
    """
    from datetime import datetime, timezone

    now_iso = datetime.now(timezone.utc).isoformat()
    t_id = thread_id or str(uuid.uuid4())

    return ComplianceState(
        thread_id=t_id,
        user_id=user_id,
        created_at=now_iso,
        original_prompt=user_prompt,
        sanitized_prompt="",
        pii_mapping={},
        detected_pii=[],
        schema_context={},
        proposed_plan=None,
        judge_evaluation=None,
        replan_count=0,
        status="PENDING_REASONING",
        approval_token=None,
        approved_by=None,
        approved_at=None,
        execution_result=None,
        error_message=None,
        messages=[],
    )
